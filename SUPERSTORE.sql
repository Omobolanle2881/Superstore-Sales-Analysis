POSTAL_CODE VARCHAR(50),
REGION VARCHAR(50),
PRODUCT_ID VARCHAR(50),
CATEGORY VARCHAR(50),
SUB_CATEGORY VARCHAR(50),
PRODUCT_NAME VARCHAR(250),
SALES DECIMAL(12,2)
);



